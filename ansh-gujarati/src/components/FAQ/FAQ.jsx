export default function FAQ() {
  const [openIndex, setOpenIndex] = useState(0);

  const toggle = (i) => setOpenIndex((current) => (current === i ? -1 : i));

  return (
    <section className="faq section section--alt" id="faq">
      <div className="container faq__grid">
        <div className="faq__intro" data-reveal="left">
          <p className="eyebrow">સામાન્ય પ્રશ્નો</p>
          <h2 className="section-title">વારંવાર પૂછાતા પ્રશ્નો</h2>
          <p className="faq__intro-text">
            ટેબ્લેટ લેવાની રીત, ફાયદા, કિંમત, ગેરંટી અને ડિલિવરી — તમારા બધા સવાલોના જવાબ એક જ
            જગ્યાએ.
          </p>
        </div>

        <div className="faq__list" data-reveal="right">
          {faqs.map((item, i) => {
            const isOpen = openIndex === i;
            const answer = Array.isArray(item.a) ? item.a : [item.a];
            return (
              <div className={`faq__item ${isOpen ? 'faq__item--open' : ''}`} key={item.q}>
                <h3 className="faq__heading">
                  <button
                    type="button"
                    id={`faq-btn-${i}`}
                    className="faq__question"
                    aria-expanded={isOpen}
                    aria-controls={`faq-panel-${i}`}
                    onClick={() => toggle(i)}
                  >
                    <span>{item.q}</span>
                    {isOpen ? <FiMinus /> : <FiPlus />}
                  </button>
                </h3>
                <div id={`faq-panel-${i}`} className="faq__answer" role="region" hidden={!isOpen}>
                  {answer.map((line) => (
                    <p key={line}>{line}</p>
                  ))}
                </div>
              </div>
            );
          })}

          <div className="faq__cta">
            <p>તમારો સવાલ અહીં નથી? અન્શ આયુર્વેદની ટીમ તમારી મદદ માટે તૈયાર છે.</p>
            <a href="#contact" className="btn btn--primary">
              અમારી સાથે વાત કરો
              <FiArrowRight />
            </a>
          </div>
        </div>
      </div>
    </section>
  );
}

